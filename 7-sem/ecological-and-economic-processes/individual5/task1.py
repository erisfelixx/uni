# Задача 12.1: модель цін для двогалузевої економіки
import numpy as np

np.set_printoptions(precision=4, suppress=True)


print("=" * 25, "ЗАДАЧА 12.1", "=" * 25)

# ПРОМИСЛОВІСТЬ (млн грн)
x11 = 1150      # на виробничі потреби промисловості
x12 = 920       # на виробничі потреби сільського господарства
y1 = 1575       # обсяг попиту населення на промислову продукцію
x1 = x11 + x12 + y1          # повний випуск промисловості

# СІЛЬСЬКЕ ГОСПОДАРСТВО (млн грн)
x21 = 820       # на виробничі потреби промисловості
x22 = 650       # на виробничі потреби сільського господарства
y2 = 1230       # обсяг попиту населення на с/г продукцію
x2 = x21 + x22 + y2          # повний випуск сільського господарства
print(f"Повні випуски: x1 = {x1} млн грн, x2 = {x2} млн грн")

# Технологічна матриця A: a[i,j] = x[i,j] / x[j]
A1 = np.array([[x11 / x1, x12 / x2],
               [x21 / x1, x22 / x2]])
E1 = np.eye(2)
print("\nТехнологічна матриця A:\n", A1)

# Матриця повних витрат B = (E - A)^(-1)
B1 = np.linalg.inv(E1 - A1)
print("\nМатриця повних витрат B = (E - A)^(-1):\n", B1)

# Перевірка моделі Леонтьєва: x = B·y має дати повні випуски
print("\nПеревірка: B·y =", B1 @ np.array([y1, y2]), " (має дорівнювати (x1, x2))")

# МОДЕЛЬ ЦІН: p = pA + s  =>  p(E - A) = s  =>  p = s·(E - A)^(-1) = s·B
s = np.array([0.15, 0.4])    # вектор доданої вартості (рядок)
p = s @ B1                   # множення рядка на матрицю (зліва)
print(f"\nВектор доданої вартості s = {s}")
print(f"Ціни: p1 = {p[0]:.4f} (промисловість),  p2 = {p[1]:.4f} (с/г)")